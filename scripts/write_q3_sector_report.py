"""从扇形版归档汇总生成中文验证报告与论文备用稿，避免手写转录数值。"""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    report=json.loads((ROOT/'results/tables/第三问/扇形版_成对验证汇总.json').read_text(encoding='utf-8'))
    stats=report['统计']; validation=stats['独立验证集']
    old,new=validation['route'],validation['sector']; comparison=validation['成对比较']
    rows=[]
    for group in ['开发集','独立验证集']:
        for variant,name in [('route','此前路线版'),('sector','扇形清空版')]:
            item=stats[group][variant]; m=item['平均指标']
            rows.append(f"| {group} | {name} | {item['全清数']}/{item['场数']} | {m['总时间_秒']:.3f} | {m['总路程_米']/1000:.3f} | {m['检测次数']:.3f} | {m['末次固定检测后路程_米']/1000:.3f} |")
    layout_rows=[]
    for layout,name in [('uniform','均匀散布'),('boundary','边界分布'),('cluster','外围聚集'),('center','中心聚集')]:
        item=validation['分布局'][layout]
        layout_rows.append(f"| {name} | {item['场数']} | {item['此前路线版平均时间_秒']:.3f} | {item['扇形版平均时间_秒']:.3f} |")
    audits='、'.join(f'{k}{v}' for k,v in report['验收合计'].items())
